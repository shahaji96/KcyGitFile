//Real time example on switch

//ATM Menu

let button = 3;
switch (button) {
    case 1:
        console.log("Check Balance");
        break;
    case 2:
        console.log("Withdraw Money");
        break;
    case 3:
        console.log("Available Balance");
        break;
    case 4:
        console.log("Deposit Money");
        break;
    default:
        console.log("Invalid option");
}

console.log("-----Langauge Selection-----")
